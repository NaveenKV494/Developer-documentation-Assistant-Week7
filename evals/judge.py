from __future__ import annotations

import json
import re
import time
from typing import Any

from google import genai
from google.genai import types
from pydantic import BaseModel, Field

from app.config import GENERATION_MODEL, JUDGE_MODEL, require_api_key


class JudgeEvaluation(BaseModel):
    faithfulness: float = Field(
        description="Score between 0.0 and 1.0 indicating if all claims are strictly supported by the context without hallucination."
    )
    relevancy: float = Field(
        description="Score between 0.0 and 1.0 indicating if the candidate answer directly and clearly addresses the question."
    )
    refusal_correctness: float = Field(
        description="1.0 if refusal behavior was appropriate (refused when unsupported, answered when supported), else 0.0."
    )
    verdict: str = Field(
        description="'PASS' if the answer is faithful, relevant, and correctly handles refusal; otherwise 'FAIL'."
    )
    score: float = Field(
        description="Overall grade from 0.0 to 1.0 (weighted composite of faithfulness, relevancy, and refusal correctness)."
    )
    reasoning: str = Field(
        description="Concise rationale explaining the grading decision and any identified errors."
    )


JUDGE_PROMPT_TEMPLATE = """You are an expert impartial AI evaluation judge specializing in developer documentation RAG systems.
Your job is to evaluate a candidate answer generated by a RAG system against the user's question and the retrieved documentation context.

### EVALUATION RUBRIC:
1. Faithfulness (0.0 - 1.0):
   - 1.0: Every factual claim in the answer is explicitly grounded in the provided context.
   - 0.5: Mostly grounded, but contains minor extrapolation or unsupported nuances.
   - 0.0: Contains clear hallucinations, contradictions, or claims not supported by the context.

2. Answer Relevancy (0.0 - 1.0):
   - 1.0: Directly addresses the user's question completely and concisely.
   - 0.5: Partially answers the question or includes irrelevant tangential information.
   - 0.0: Does not answer the question asked or answers an unrelated topic.

3. Refusal Correctness (1.0 or 0.0):
   - 1.0: The candidate correctly refused an unsupported question ("I couldn't find that information...") OR correctly answered a supported question.
   - 0.0: The candidate falsely refused a question whose evidence was present in the context, OR gave an ungrounded fabricated answer to an unsupported question.

4. Verdict:
   - "PASS" if score >= 0.75 and no hallucination or false refusal occurred.
   - "FAIL" if any hallucination, false refusal, or significant factual error is detected.

USER QUESTION:
{question}

RETRIEVED DOCUMENTATION CONTEXT:
{context}

CANDIDATE ANSWER TO EVALUATE:
{answer}

OUTPUT INSTRUCTIONS:
Return a JSON object strictly adhering to this schema:
{schema}
"""


import hashlib
from pathlib import Path

CACHE_FILE = Path(__file__).parent / ".judge_cache.json"


def _load_cache() -> dict[str, dict]:
    if not CACHE_FILE.exists():
        return {}
    try:
        with open(CACHE_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {}


def _save_cache(cache: dict[str, dict]) -> None:
    try:
        with open(CACHE_FILE, "w", encoding="utf-8") as f:
            json.dump(cache, f, indent=2, ensure_ascii=False)
    except Exception:
        pass


def _cache_key(question: str, context: str, answer: str) -> str:
    raw = f"{question.strip()}|||{context.strip()}|||{answer.strip()}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def evaluate_with_judge(
    question: str,
    context: str,
    answer: str,
    api_key: str | None = None,
    use_cache: bool = True,
) -> JudgeEvaluation:
    """Evaluate a candidate RAG response using the validated LLM-as-a-Judge."""
    key = _cache_key(question, context, answer)
    if use_cache:
        cache = _load_cache()
        if key in cache:
            return JudgeEvaluation.model_validate(cache[key])

    client = genai.Client(api_key=api_key or require_api_key())

    prompt = JUDGE_PROMPT_TEMPLATE.format(
        question=question,
        context=context if context.strip() else "[NO CONTEXT PROVIDED]",
        answer=answer if answer.strip() else "[EMPTY ANSWER]",
        schema=JudgeEvaluation.model_json_schema(),
    )

    max_attempts = 6
    for attempt in range(max_attempts):
        try:
            # Polite pacing delay to avoid bursting through RPM limits
            time.sleep(1.0)
            response = client.models.generate_content(
                model=JUDGE_MODEL,
                contents=prompt,
                config=types.GenerateContentConfig(
                    response_mime_type="application/json",
                    response_schema=JudgeEvaluation,
                    temperature=0.0,
                ),
            )
            break
        except Exception as exc:
            if attempt == max_attempts - 1:
                # Fallback conservative judgment on permanent failure
                return JudgeEvaluation(
                    faithfulness=0.0,
                    relevancy=0.0,
                    refusal_correctness=0.0,
                    verdict="FAIL",
                    score=0.0,
                    reasoning=f"Judge generation failed after {max_attempts} retries: {exc}",
                )

            message = str(exc)
            delay = min(75.0, 5.0 * (2 ** attempt))
            retry_match = re.search(r"retry(?:\s+in)?\s+([0-9]+(?:\.[0-9]+)?)\s*s", message, re.I)
            if retry_match:
                delay = min(75.0, max(delay, float(retry_match.group(1)) + 2.0))
            print(f"Judge rate limited; waiting {delay:.1f}s before retry (attempt {attempt + 1}/{max_attempts})...")
            time.sleep(delay)

    try:
        if getattr(response, "parsed", None) is not None:
            result = JudgeEvaluation.model_validate(response.parsed)
        else:
            result = JudgeEvaluation.model_validate_json(response.text)
    except Exception as exc:
        result = JudgeEvaluation(
            faithfulness=0.0,
            relevancy=0.0,
            refusal_correctness=0.0,
            verdict="FAIL",
            score=0.0,
            reasoning=f"Failed to parse structured judge response: {exc}",
        )

    # Cache successful judgment
    if use_cache and result.score > 0:
        cache = _load_cache()
        cache[key] = result.model_dump()
        _save_cache(cache)

    return result

